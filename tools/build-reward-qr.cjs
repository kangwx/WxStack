// Bundle the installed QR encoder for Cocos without runtime CDN/network dependencies.
const fs = require('node:fs');
const path = require('node:path');
const ids = new Map(), modules = [];
function add(file) {
  if (ids.has(file)) return ids.get(file);
  const id = modules.length; ids.set(file, id); modules.push('');
  const source = fs.readFileSync(file, 'utf8').replace(/require\(['"]([^'"]+)['"]\)/g,
    (_, name) => `load(${add(require.resolve(name, { paths: [path.dirname(file)] }))})`);
  modules[id] = `${id}: function(module, exports, load) {\n${source}\n}`;
  return id;
}
const entry = add(require.resolve('qrcode/lib/core/qrcode'));
const licenses = ['qrcode/license', 'dijkstrajs/LICENSE.md'].map(name => fs.readFileSync(require.resolve(name), 'utf8')).join('\n\n');
const output = `// @ts-nocheck\n// Generated by tools/build-reward-qr.cjs. Do not edit.\n/*\n${licenses}\n*/\nconst modules = {\n${modules.join(',\n')}\n};\nconst cache = {};\nfunction load(id) { if (!cache[id]) { const module = cache[id] = { exports: {} }; modules[id](module, module.exports, load); } return cache[id].exports; }\nexport function encodeRewardQr(url: string): { size: number; modules: number[] } {\n const qr = load(${entry}).create(url, { errorCorrectionLevel: 'M' }).modules;\n return { size: qr.size, modules: Array.from(qr.data) };\n}\n`;
fs.writeFileSync(path.join(__dirname, '../assets/scripts/RewardQrEncoder.ts'), output);
